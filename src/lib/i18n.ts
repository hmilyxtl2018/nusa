const TABLES: Record<Lang, Record<I18nKey, string>> = {
  en,
  id,
  ms,
  th,
  vi,
  fil,
  zh,
  km,
  lo,
  my,
};

export function t(lang: Lang | null, key: I18nKey, vars?: Record<string, string | number>) {
  const table = TABLES[lang ?? "en"] ?? en;
  let out = table[key] ?? en[key] ?? key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      out = out.replaceAll(`{${k}}`, String(v));
    }
  }
  return out;
}

export function greetingKey(hour: number): I18nKey {
  if (hour < 11) return "home.g.morning";
  if (hour < 16) return "home.g.midday";
  if (hour < 21) return "home.g.evening";
  return "home.g.late";
}
